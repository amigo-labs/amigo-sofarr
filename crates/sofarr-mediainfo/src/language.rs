/// ISO 639-2/B code (`ger`, `eng`, `und`) from an ISO 639-2/B or /T code (`deu` -> `ger`), a 639-1 code (`de`) or a BCP 47 tag (`de-DE`); unknown -> `und`.
pub fn language_code(raw: &str) -> String {
    let primary = raw
        .trim()
        .split(['-', '_'])
        .next()
        .unwrap_or_default()
        .to_ascii_lowercase();
    let from_table = CODES.iter().find_map(|(alpha2, bib, term)| {
        (primary == *alpha2 || primary == *bib || primary == *term).then_some(*bib)
    });
    let code = from_table.or_else(|| {
        EXTRA
            .iter()
            .find_map(|(from, to)| (primary == *from).then_some(*to))
    });
    code.unwrap_or("und").to_string()
}

/// The same from an English language name as Radarr/Sonarr print it (`German`, `English`, `French`, …); unknown -> None.
pub fn language_from_name(name: &str) -> Option<String> {
    let name = name.trim();
    NAMES
        .iter()
        .find(|(known, _)| known.eq_ignore_ascii_case(name))
        .map(|(_, code)| (*code).to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn codes_map_to_iso_639_2_b() {
        let cases = [
            ("ger", "ger"),
            ("deu", "ger"),
            ("de", "ger"),
            ("de-DE", "ger"),
            ("DE_at", "ger"),
            ("eng", "eng"),
            ("en-US", "eng"),
            ("fra", "fre"),
            ("fr-CA", "fre"),
            ("zho", "chi"),
            ("zh-Hans", "chi"),
            ("nld", "dut"),
            ("ces", "cze"),
            ("pt-BR", "por"),
            ("es-419", "spa"),
            ("sqi", "alb"),
            ("iw", "heb"),
            ("fil", "fil"),
            ("und", "und"),
            ("", "und"),
            ("xx", "und"),
            ("qaa", "und"),
            ("klingon", "und"),
        ];
        for (raw, expected) in cases {
            assert_eq!(language_code(raw), expected, "{raw}");
        }
    }

    #[test]
    fn every_table_code_round_trips() {
        for (alpha2, bib, term) in CODES {
            assert_eq!(language_code(alpha2), *bib);
            assert_eq!(language_code(bib), *bib);
            assert_eq!(language_code(term), *bib);
        }
    }

    #[test]
    fn names_map_to_codes() {
        let cases = [
            ("German", Some("ger")),
            ("english", Some("eng")),
            (" French ", Some("fre")),
            ("Portuguese (Brazil)", Some("por")),
            ("Spanish (Latino)", Some("spa")),
            ("Flemish", Some("dut")),
            ("Unknown", Some("und")),
            ("Klingon", None),
            ("", None),
        ];
        for (name, expected) in cases {
            assert_eq!(language_from_name(name).as_deref(), expected, "{name}");
        }
        for (_, code) in NAMES {
            assert_eq!(language_code(code), *code, "{code}");
        }
    }
}
